package aula05;

public class Licao {
    public static void main(String[] args) {
        // oque são assignment operators?
        // são operadores que são utilizados para dar valor para uma variavel
        // = , += , -=, *=, /=, %=, &= |=, ^=, >>=, <<=

        // Utilizando os operadores:

        int a = 10;
        a = 9;
        System.out.println(a);
        a += 1;
        System.out.println(a);
        a -= 2;
        System.out.println(a);
        a *= 2;
        System.out.println(a);
        a /= 2;
        System.out.println(a);
        a %= 2;
        System.out.println(a);
        a &= 3;
        System.out.println(a);
        a |= 3;
        System.out.println(a);
        a ^= 2;
        System.out.println(a);
        a >>= 4;
        System.out.println(a);
        a <<= 10;
        System.out.println(a);


    }
}