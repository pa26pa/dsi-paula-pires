package aula07;

public class Switch {
    public static void main(String[] args) {
        int a = 2;

        switch(a) {
        case 0:
            System.out.println("Desligado");
            break;
        case 1:
            System.out.println("Ligado");
            break;
        default:
            System.out.println("Não tem comooooooo :(");
        }
    }
}
